/** Bundle the pinned Ajv validator for the local demo and other browser consumers. */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["js/cookbook-validator.js"],
  outfile: "assets/cookbook-validator.js",
  bundle: true,
  platform: "browser",
  format: "iife",
  globalName: "FastVideoSchema",
  target: ["es2020"],
  minify: true,
  metafile: true,
  legalComments: "inline",
  banner: { js: "/*! Generated by docs/build-validator.mjs. Licenses: cookbook-validator.LICENSE.txt */" },
  footer: { js: 'if (typeof module !== "undefined" && module.exports) module.exports = FastVideoSchema;' },
});

// Preserve the notices of the packages whose code is actually included in the bundle.
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const parts = input.split("node_modules/").at(-1).split("/");
  if (input.includes("node_modules/")) {
    packages.add(parts[0].startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]);
  }
}
const notices = [];
for (const name of [...packages].sort()) {
  let license;
  for (const filename of ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENSE-MIT"]) {
    try {
      license = await readFile(join(root, "node_modules", name, filename), "utf8");
      break;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  if (!license) throw new Error(`Missing license for bundled package ${name}`);
  notices.push(`${name}\n${"=".repeat(name.length)}\n${license}`);
}
await writeFile(join(root, "assets/cookbook-validator.LICENSE.txt"), notices.join("\n\n"));
console.log("Built assets/cookbook-validator.js and third-party license notices.");
